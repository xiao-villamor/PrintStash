"""The storage transport registry.

Adding a transport is one module in this package plus its registration below:

1. Write ``<name>.py`` with its ``ProviderConfig`` subclass and a ``Transport``
   (local) or ``RemoteTransport`` descriptor.
2. Add its ``TransportKind`` member, and the same value to
   ``LibrarySourceKind`` (an autogenerated migration widens the CHECK).
3. Register the descriptor in ``TRANSPORTS`` and its config in
   ``StorageProviderConfig``.

Repository tests then name every remaining step: the Dockerfile's
``OPENDAL_SERVICES``, the frontend's remote kinds and the generated provider
documentation.
"""

from __future__ import annotations

from typing import Annotated

from pydantic import Field

from app.modules.storage.transports.base import (
    ProviderConfig,
    RemoteTransport,
    Transport,
    TransportKind,
)
from app.modules.storage.transports.gdrive import (
    GoogleDriveProviderConfig,
    GoogleDriveTransport,
)
from app.modules.storage.transports.local import LocalProviderConfig, LocalTransport
from app.modules.storage.transports.s3 import S3ProviderConfig, S3Transport
from app.modules.storage.transports.sftp import SFTPProviderConfig, SFTPTransport
from app.modules.storage.transports.webdav import (
    WebDAVProviderConfig,
    WebDAVTransport,
)

# Catalogue order: the provider list, the documentation and the forms follow it.
TRANSPORTS: tuple[Transport, ...] = (
    LocalTransport(),
    S3Transport(),
    WebDAVTransport(),
    SFTPTransport(),
    GoogleDriveTransport(),
)

StorageProviderConfig = Annotated[
    LocalProviderConfig
    | S3ProviderConfig
    | WebDAVProviderConfig
    | SFTPProviderConfig
    | GoogleDriveProviderConfig,
    Field(discriminator="provider"),
]

_BY_KIND: dict[TransportKind, Transport] = {
    transport.kind: transport for transport in TRANSPORTS
}


def transport(kind: TransportKind) -> Transport:
    return _BY_KIND[kind]


def remote_transport(kind: TransportKind) -> RemoteTransport:
    registered = _BY_KIND[kind]
    if not isinstance(registered, RemoteTransport):
        raise ValueError(f"{kind.value} is not a remote transport")
    return registered


def remote_transports() -> tuple[RemoteTransport, ...]:
    return tuple(t for t in TRANSPORTS if isinstance(t, RemoteTransport))


def transport_for_config(config: ProviderConfig) -> Transport:
    for registered in TRANSPORTS:
        if isinstance(config, registered.config_model):
            return registered
    raise ValueError("storage_provider_unknown")


def config_models() -> tuple[type[ProviderConfig], ...]:
    return tuple(t.config_model for t in TRANSPORTS)
