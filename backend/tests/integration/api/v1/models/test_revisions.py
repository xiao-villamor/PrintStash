GCODE = b"; generated by OrcaSlicer\nG28\n"


def _gcode_files(body: dict) -> list[dict]:
    return [row for row in body["files"] if row["file_type"] == "gcode"]


def _large_gcode(min_bytes: int = 1_200_000) -> bytes:
    """A body over nginx's default 1 MB limit, which the app must still accept."""
    payload = b"; generated by OrcaSlicer\nG90\nG1 X1 Y1 E1\n"
    payload += b"; padding to exceed nginx default body limit\n" * (min_bytes // 45)
    return payload


