"""G-code revisions: adding one, labelling it, and taking one away.

A model accumulates G-code over time — reprints, tuned profiles, a fix for a warping
corner — and the library's job is to say which one to print *now*. That is the recommended
revision, and the invariant behind every test here is that a model with G-code has
**exactly one**: the first upload becomes it automatically, marking a new one demotes the
old one, and deleting the recommended one promotes the newest survivor rather than leaving
a model with G-code and nothing to print.

"Exactly one" is also scoped per model. Promoting a revision on one model must not touch
another's, which is the kind of thing a `WHERE` clause forgets.

Deletes are soft, so a revision can come back, and the file's own metadata comes back with
it. What must not survive a delete is a stale pointer: a model whose thumbnail came from
the deleted file has to let go of it, or the grid renders a thumbnail for bytes that are
no longer part of the model.
"""

