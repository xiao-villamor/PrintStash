class TestDeleteRevision:
    def test_hides_the_revision_from_the_model(
        self, client: TestClient, auth_headers, model: Model, make_file
    ) -> None:
        keep = make_file(model)
        drop = make_file(model)

        response = client.delete(
            f"/api/v1/models/{model.id}/files/{drop.id}/revision", headers=auth_headers
        )

        assert response.status_code == 200, response.text
        assert [row["id"] for row in response.json()["files"]] == [keep.id]

    def test_keeps_the_row_so_the_revision_can_come_back(
        self,
        client: TestClient,
        db_session: Session,
        auth_headers,
        model: Model,
        make_file,
    ) -> None:
        make_file(model)
        drop = make_file(model)

        client.delete(
            f"/api/v1/models/{model.id}/files/{drop.id}/revision", headers=auth_headers
        )

        db_session.refresh(drop)
        assert drop.deleted_at is not None

    def test_promotes_the_newest_survivor_when_the_recommended_one_goes(
        self,
        client: TestClient,
        db_session: Session,
        auth_headers,
        model: Model,
        make_file,
    ) -> None:
        make_file(model)
        middle = make_file(model)
        newest = make_file(model)
        middle.is_recommended = True
        db_session.add(middle)
        db_session.commit()

        response = client.delete(
            f"/api/v1/models/{model.id}/files/{middle.id}/revision",
            headers=auth_headers,
        )

        # Otherwise the model still has G-code and nothing to print.
        recommended = [
            row["id"] for row in response.json()["files"] if row["is_recommended"]
        ]
        assert recommended == [newest.id]

    def test_leaves_nothing_recommended_when_the_last_revision_goes(
        self,
        client: TestClient,
        db_session: Session,
        auth_headers,
        model: Model,
        make_file,
    ) -> None:
        only = make_file(model)
        only.is_recommended = True
        db_session.add(only)
        db_session.commit()

        response = client.delete(
            f"/api/v1/models/{model.id}/files/{only.id}/revision", headers=auth_headers
        )

        assert response.json()["files"] == []
        db_session.refresh(only)
        assert only.is_recommended is False

