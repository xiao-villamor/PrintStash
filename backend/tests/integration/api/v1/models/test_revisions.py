    def test_refuses_a_file_with_no_name(
        self, client: TestClient, auth_headers, model: Model, local_storage
    ) -> None:
        boundary = "revisionboundary"
        body = (
            f"--{boundary}\r\n"
            'Content-Disposition: form-data; name="file"; filename=""\r\n'
            "Content-Type: text/plain\r\n\r\n"
            "hi\r\n"
            f"--{boundary}--\r\n"
        ).encode()

        response = client.post(
            f"/api/v1/models/{model.id}/gcode-revisions",
            content=body,
            headers={
                **auth_headers,
                "content-type": f"multipart/form-data; boundary={boundary}",
            },
        )

        assert response.status_code == 400, response.text
        assert response.json()["detail"] == "filename_required"

    def test_refuses_a_file_past_the_upload_cap(
        self,
        client: TestClient,
        auth_headers,
        model: Model,
        local_storage,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        def too_large(*_args: object, **_kwargs: object):
            raise storage.UploadTooLarge("upload_too_large")

        monkeypatch.setattr("app.api.v1.models.storage.stream_to_path", too_large)

        response = client.post(
            f"/api/v1/models/{model.id}/gcode-revisions",
            headers=auth_headers,
            files={"file": ("rev.gcode", GCODE, "text/plain")},
        )

        # The route's own per-file cap, which a client can now actually see: the
        # request ceiling sits above it, so a file over the file limit reaches
        # route code instead of being answered as `request_too_large`.
        assert response.status_code == 413, response.text
        assert response.json()["detail"] == "upload_too_large"

    def test_removes_the_staged_file_when_the_import_fails(
        self,
        client: TestClient,
        auth_headers,
        model: Model,
        local_storage,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        staged: list[Path] = []

        def failing(**kwargs):
            staged.append(kwargs["staged_path"])
            raise RuntimeError("boom")

        monkeypatch.setattr("app.api.v1.models.add_gcode_revision_to_model", failing)

        with pytest.raises(RuntimeError, match="boom"):
            client.post(
                f"/api/v1/models/{model.id}/gcode-revisions",
                headers=auth_headers,
                files={"file": ("rev.gcode", GCODE, "text/plain")},
            )

        # A staged file nobody owns is a staging directory that only grows.
        assert staged and not staged[0].exists()

    def test_rejects_an_unauthenticated_caller(
        self, client: TestClient, model: Model, local_storage
    ) -> None:
        response = client.post(
            f"/api/v1/models/{model.id}/gcode-revisions",
            files={"file": ("rev.gcode", GCODE, "text/plain")},
        )

        assert response.status_code == 401, response.text


