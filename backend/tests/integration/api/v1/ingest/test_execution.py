"""Synchronous ingestion I/O must leave the ASGI event loop responsive.

The dependency deliberately waits for a callback on the request's event loop.
A synchronous call on that loop cannot satisfy the handshake before its timeout;
a complete request command in the bounded thread pool can. This avoids comparing
fragile wall-clock percentiles on shared CI hosts.
"""

from __future__ import annotations

import asyncio
import io
import json
import zipfile

import httpx
import pytest

from app.db.models import IngestRequestKind, JobState
from app.db.session import get_session_factory, override_session_factory
from app.modules.storage import storage
from tests.factories import build_user
from tests.factories.identity import bearer
from tests.fakes.thread_sessions import ThreadBoundSessionFactory


class TestIngestExecution:
    @pytest.fixture(autouse=True)
    def _thread_owned_command_sessions(self, db_session):
        factory = ThreadBoundSessionFactory(db_session.get_bind())
        previous = get_session_factory()
        override_session_factory(factory)
        try:
            yield factory
            assert factory.opened_count > 0
            assert factory.active_count == 0
        finally:
            override_session_factory(previous)

    @pytest.mark.asyncio
    @pytest.mark.parametrize(
        "endpoint,filename,content",
        [
            pytest.param(
                "model", "source.stl", b"solid source\nendsolid source", id="model"
            ),
            pytest.param(
                "orca", "slice.gcode", b"; generated by OrcaSlicer\nG1 X1 Y1", id="orca"
            ),
        ],
    )
    async def test_keeps_loop_responsive_during_upload_submission(
        self,
        app,
        auth_headers,
        work_engine,
        monkeypatch,
        loop_handshake,
        endpoint,
        filename,
        content,
    ):
        wait_for_loop, observations = loop_handshake
        submit = work_engine.submit

        def delayed_submit(submission):
            wait_for_loop()
            return submit(submission)

        monkeypatch.setattr(work_engine, "submit", delayed_submit)

        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://test"
        ) as client:
            response = await client.post(
                f"/api/v1/ingest/{endpoint}",
                headers=auth_headers,
                files={"file": (filename, content, "application/octet-stream")},
            )

        assert response.status_code == 202, response.text
        assert observations == [True]

