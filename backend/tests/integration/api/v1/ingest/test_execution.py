    @pytest.mark.asyncio
    @pytest.mark.parametrize("kind", ["model_files", "collection"])
    async def test_keeps_loop_responsive_during_manifest_selection(
        self,
        app,
        db_session,
        make_ingest_request,
        work_engine,
        monkeypatch,
        loop_handshake,
        kind,
    ):
        owner = build_user(db_session, "selection-owner", superuser=True)
        if kind == "model_files":
            manifest = {
                "kind": kind,
                "page_url": "https://printables.com/model/1",
                "files": [{"file_id": "1", "name": "part.stl", "file_type": "stl"}],
            }
            route = "url/files"
            selection = {"file_ids": ["1"]}
        else:
            manifest = {
                "kind": kind,
                "title": "Parts",
                "target_collection": "Parts",
                "members": [
                    {
                        "source_id": "1",
                        "title": "Part",
                        "page_url": "https://printables.com/model/1",
                    }
                ],
            }
            route = "collection"
            selection = {"member_ids": ["1"]}
        request = make_ingest_request(
            owner,
            kind=IngestRequestKind.URL,
            state=JobState.COMPLETED,
            manifest_json=json.dumps(manifest),
        )
        wait_for_loop, observations = loop_handshake
        submit = work_engine.submit

        def delayed_submit(submission):
            wait_for_loop()
            return submit(submission)

        monkeypatch.setattr(work_engine, "submit", delayed_submit)
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://test"
        ) as client:
            response = await client.post(
                f"/api/v1/ingest/{route}/{request.job_id}/select",
                headers=bearer(owner),
                json=selection,
            )

        assert response.status_code == 202, response.text
        assert observations == [True]

    @pytest.mark.asyncio
    async def test_keeps_loop_responsive_during_archive_selection(
        self,
        app,
        auth_headers,
        work_engine,
        monkeypatch,
        loop_handshake,
    ):
        content = io.BytesIO()
        with zipfile.ZipFile(content, "w") as archive:
            archive.writestr("source.stl", b"solid source\nendsolid source")
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=app), base_url="http://test"
        ) as client:
            inspected = await client.post(
                "/api/v1/ingest/archive/inspect",
                headers=auth_headers,
                files={"file": ("source.zip", content.getvalue(), "application/zip")},
            )
            assert inspected.status_code == 202, inspected.text
            # Only ZIP inspection runs here; no model is imported or rendered.
            await asyncio.to_thread(work_engine.drain)
            wait_for_loop, observations = loop_handshake
            submit = work_engine.submit

            def delayed_submit(submission):
                wait_for_loop()
                return submit(submission)

            monkeypatch.setattr(work_engine, "submit", delayed_submit)
            response = await client.post(
                f"/api/v1/ingest/archive/{inspected.json()['job_id']}/select",
                headers=auth_headers,
                json={"names": ["source.stl"]},
            )

        assert response.status_code == 202, response.text
        assert observations == [True]
