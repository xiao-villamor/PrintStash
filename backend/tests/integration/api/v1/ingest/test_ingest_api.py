def _large_gcode(min_bytes: int = 1_200_000) -> bytes:
    payload = b"; generated by OrcaSlicer\nG90\nG1 X1 Y1 E1\n"
    payload += b"; padding to exceed nginx default body limit\n" * (min_bytes // 45)
    return payload


def _large_cube_stl(min_bytes: int = 1_200_000) -> bytes:
    lines = _cube_stl().splitlines()
    body = b"\n".join(lines[1:-1]) + b"\n"
    repeat_count = min_bytes // len(body) + 1
    return b"solid large-cube\n" + body * repeat_count + b"endsolid large-cube\n"


def _over_cap_binary_stl(n_triangles: int = 1_001) -> bytes:
    output = io.BytesIO()
    output.write(b"issue-67".ljust(80, b"\x00"))
    output.write(struct.pack("<I", n_triangles))
    record = struct.Struct("<12fH")
    for index in range(n_triangles):
        x = float(index % 100)
        y = float((index // 100) % 100)
        output.write(
            record.pack(
                0,
                0,
                1,
                x,
                y,
                0,
                x + 0.8,
                y,
                0,
                x,
                y + 0.8,
                0,
                0,
            )
        )
    return output.getvalue()


