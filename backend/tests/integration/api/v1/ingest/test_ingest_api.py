def _post_empty_filename_multipart(
    client: TestClient, url: str, headers: dict[str, str]
) -> Any:
    """Post a multipart body whose file part has an explicit empty filename.

    ``httpx``'s ``files=`` helper drops the ``filename`` attribute entirely
    when given an empty string (turning the part into a plain form field, not
    an ``UploadFile``), so the empty-filename branch can only be reached by
    building the multipart body by hand.
    """
    boundary = "ingesttestboundary"
    body = (
        f"--{boundary}\r\n"
        'Content-Disposition: form-data; name="file"; filename=""\r\n'
        "Content-Type: text/plain\r\n\r\n"
        "hi\r\n"
        f"--{boundary}--\r\n"
    ).encode()
    return client.post(
        url,
        content=body,
        headers={
            **headers,
            "content-type": f"multipart/form-data; boundary={boundary}",
        },
    )


